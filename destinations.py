def _validate_and_align_day_fields(df: pd.DataFrame) -> pd.DataFrame:
    """Garantisce le invarianti sui campi giorno che il Trip Builder assume
    quando somma le tappe di un itinerario (vedi trip_builder.score_trip):

        1 <= minimum_days <= ideal_days <= days_max   (e days_min <= days_max)

    Il dataset attuale rispetta già queste regole per costruzione (vedi
    sotto), ma questa funzione è una rete di sicurezza per quando il dataset
    cresce a mano: se days_min/days_max o i campi derivati venissero
    aggiornati in modo incoerente, li corregge invece di lasciare che il
    motore produca punteggi silenziosamente sbagliati.
    """
    swapped = df["days_min"] > df["days_max"]
    if swapped.any():
        df.loc[swapped, ["days_min", "days_max"]] = df.loc[swapped, ["days_max", "days_min"]].to_numpy()

    df["minimum_days"] = df["minimum_days"].clip(lower=1, upper=df["days_max"])
    df["ideal_days"] = df["ideal_days"].clip(lower=df["minimum_days"], upper=df["days_max"])
    return df


